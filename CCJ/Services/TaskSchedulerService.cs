using System;
using System.Collections.Generic;
using System.IO;
using CCJ.Models;
using Microsoft.Win32.TaskScheduler;

namespace CCJ.Services
{
    /// <summary>
    /// Creates, updates and reads the three scheduled tasks.
    ///
    /// The Windows password is only ever a method parameter here. It is never stored in a field,
    /// never written to jobs.json, app.log or anywhere else on disk, and never sent anywhere
    /// except to the Task Scheduler API that needs it to register a task that runs while the user
    /// is logged off.
    /// </summary>
    public class TaskSchedulerService
    {
        public const string TaskNamePrefix = "CCJ Backup ";

        /// <summary>Every third Sunday, as the spec requires.</summary>
        public const short WeeksInterval = 3;

        /// <summary>
        /// Creates the task, or updates it in place if it already exists.
        /// </summary>
        public void CreateOrUpdate(JobConfig job, string voxRoot, string userName, string password)
        {
            if (job == null) throw new ArgumentNullException("job");
            if (string.IsNullOrEmpty(voxRoot)) throw new ArgumentException("voxRoot is required.", "voxRoot");
            if (string.IsNullOrEmpty(userName)) throw new ArgumentException("A user name is required.", "userName");
            if (string.IsNullOrEmpty(password)) throw new ArgumentException("A password is required.", "password");

            List<string> errors = Validation.ValidateJob(job);
            if (errors.Count > 0) throw new ValidationException(errors);

            string scriptPath = job.ScriptPath(voxRoot);
            if (!File.Exists(scriptPath))
            {
                throw new FileNotFoundException(
                    "The script " + scriptPath + " does not exist yet. Save the jobs first so the " +
                    "script is written, then create the task.", scriptPath);
            }

            using (TaskService service = new TaskService())
            {
                TaskDefinition definition = service.NewTask();

                definition.RegistrationInfo.Author = "CCJ";
                definition.RegistrationInfo.Description =
                    "Robocopy backup of " + job.SourcePath + " to " + job.DestinationPath +
                    ". Copy only, nothing is deleted. Generated by CCJ.";

                // Run after a missed start, and never two copies of the same job at once.
                definition.Settings.StartWhenAvailable = true;
                definition.Settings.MultipleInstances = TaskInstancesPolicy.IgnoreNew;
                definition.Settings.Enabled = job.Enabled;

                // A backup that is skipped because the machine is on battery is a silent failure,
                // so these two are turned off deliberately.
                definition.Settings.DisallowStartIfOnBatteries = false;
                definition.Settings.StopIfGoingOnBatteries = false;

                WeeklyTrigger trigger = new WeeklyTrigger();
                trigger.DaysOfWeek = DaysOfTheWeek.Sunday;
                trigger.WeeksInterval = WeeksInterval;

                // Date and time both come from the job, so the run can be put at a quiet hour
                // instead of always midnight.
                trigger.StartBoundary = job.FirstRunDate;
                definition.Triggers.Add(trigger);

                definition.Actions.Add(new ExecAction(Quote(scriptPath), null, voxRoot));

                definition.Principal.LogonType = TaskLogonType.Password;
                definition.Principal.UserId = userName;

                service.RootFolder.RegisterTaskDefinition(
                    job.TaskName,
                    definition,
                    TaskCreation.CreateOrUpdate,
                    userName,
                    password,
                    TaskLogonType.Password,
                    null);
            }

            AppLog.Info("Registered task \"" + job.TaskName + "\" for " + scriptPath +
                        " (enabled=" + job.Enabled + ", first run " +
                        job.FirstRunDate.ToString("yyyy-MM-dd HH:mm") + ", every " + WeeksInterval +
                        " weeks on Sunday).");
        }

        /// <summary>
        /// Enables or disables an existing task. Does not need the password, because the stored
        /// credential is left untouched.
        /// </summary>
        public bool SetEnabled(JobConfig job, bool enabled)
        {
            using (TaskService service = new TaskService())
            {
                Task task = service.GetTask(job.TaskName);
                if (task == null) return false;

                task.Enabled = enabled;
                AppLog.Info("Task \"" + job.TaskName + "\" enabled=" + enabled);
                return true;
            }
        }

        public bool Exists(JobConfig job)
        {
            using (TaskService service = new TaskService())
            {
                return service.GetTask(job.TaskName) != null;
            }
        }

        /// <summary>
        /// Whether the job's task is running at this moment, and when it started. Used by the
        /// progress display to attach to a run that began while CCJ was closed, such as the
        /// Sunday 00:00 one.
        /// </summary>
        public TaskRunInfo GetRunInfo(JobConfig job)
        {
            using (TaskService service = new TaskService())
            {
                Task task = service.GetTask(job.TaskName);
                if (task == null || task.State != TaskState.Running)
                    return new TaskRunInfo(false, null);

                DateTime? started = null;
                DateTime last = task.LastRunTime;
                if (last.Year > 2000) started = last;
                return new TaskRunInfo(true, started);
            }
        }

        /// <summary>Starts the task now. The caller must have confirmed with the user first.</summary>
        public void RunNow(JobConfig job)
        {
            using (TaskService service = new TaskService())
            {
                Task task = service.GetTask(job.TaskName);
                if (task == null)
                {
                    throw new InvalidOperationException(
                        "There is no task named \"" + job.TaskName + "\" yet. Use Save first to " +
                        "create it.");
                }
                task.Run();
                AppLog.Info("Task \"" + job.TaskName + "\" started on request.");
            }
        }

        /// <summary>
        /// Asks Task Scheduler to end the run. It ends the script, but robocopy is a child process
        /// and can outlive it, which is why <see cref="CopyControl"/> also deals with robocopy
        /// itself. Nothing on the destination is removed: whatever had been copied stays.
        /// </summary>
        public bool Stop(JobConfig job)
        {
            using (TaskService service = new TaskService())
            {
                Task task = service.GetTask(job.TaskName);
                if (task == null) return false;

                task.Stop();
                AppLog.Info("Task \"" + job.TaskName + "\" was stopped on request.");
                return true;
            }
        }

        public bool Delete(JobConfig job)
        {
            using (TaskService service = new TaskService())
            {
                Task task = service.GetTask(job.TaskName);
                if (task == null) return false;

                service.RootFolder.DeleteTask(job.TaskName, false);
                AppLog.Info("Deleted task \"" + job.TaskName + "\".");
                return true;
            }
        }

        /// <summary>
        /// Status of one job for the dashboard. Never throws: a problem is reported in
        /// <see cref="JobStatus.Error"/> so one broken task cannot blank the whole grid.
        /// </summary>
        public JobStatus GetStatus(JobConfig job)
        {
            JobStatus status = new JobStatus();
            status.Key = job.Key;

            try
            {
                using (TaskService service = new TaskService())
                {
                    Task task = service.GetTask(job.TaskName);
                    if (task == null)
                    {
                        status.TaskExists = false;
                        return status;
                    }

                    status.TaskExists = true;
                    status.TaskEnabled = task.Enabled;
                    status.TaskState = task.State.ToString();
                    status.LastTaskResult = task.LastTaskResult;

                    DateTime next = task.NextRunTime;
                    if (next.Year > 1900) status.NextRun = next;

                    DateTime last = task.LastRunTime;
                    if (last.Year > 1900) status.LastRun = last;
                }
            }
            catch (Exception ex)
            {
                AppLog.Error("Could not read the status of task \"" + job.TaskName + "\".", ex);
                status.Error = ex.Message;
            }
            return status;
        }

        /// <summary>
        /// cmd.exe needs the path quoted when it contains spaces, which it does whenever the Vox
        /// root sits under a user folder.
        /// </summary>
        private static string Quote(string path)
        {
            if (string.IsNullOrEmpty(path)) return path;
            if (path.StartsWith("\"")) return path;
            return "\"" + path + "\"";
        }
    }
}
